/**
 * Turns catalog/catalog.json into CatalogData.kt (SPEC S26). Lists are split into functions of
 * at most 50 entries so no generated method nears the JVM's 64 KB method limit.
 * Unknown JSON keys are ignored and optional keys default, so later phases can add fields.
 */
abstract class GenerateCatalogSource : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val catalogJson: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val chunk = 50

        @Suppress("UNCHECKED_CAST")
        val root = groovy.json.JsonSlurper().parse(catalogJson.get().asFile) as Map<String, Any?>

        fun lit(value: Any?): String {
            if (value == null) return "null"
            val escaped =
                value
                    .toString()
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("\$", "\\\$")
                    .replace("\n", "\\n")
                    .replace("\r", "\\r")
            return "\"$escaped\""
        }

        fun list(key: String): List<Map<String, Any?>> {
            @Suppress("UNCHECKED_CAST")
            return (root[key] as? List<Map<String, Any?>>).orEmpty()
        }

        val paywalls = mapOf("none" to "NONE", "metered" to "METERED", "hard" to "HARD")
        val sections =
            listOf(
                Triple(
                    "topics",
                    "Topic",
                    list("topics").map { "Topic(${lit(it["id"])}, ${lit(it["name"])}, ${lit(it["description"])})" },
                ),
                Triple(
                    "outlets",
                    "Outlet",
                    list("outlets").map {
                        val paywall =
                            paywalls[it["paywall"]] ?: error("Outlet ${it["id"]}: bad paywall ${it["paywall"]}")
                        val popularity = (it["popularity"] as Number).toDouble()
                        "Outlet(${lit(it["id"])}, ${lit(it["name"])}, ${lit(it["domain"])}, " +
                            "PaywallStatus.$paywall, $popularity)"
                    },
                ),
                Triple(
                    "feeds",
                    "CatalogFeed",
                    list("feeds").map {
                        @Suppress("UNCHECKED_CAST")
                        val topics = (it["topics"] as List<Any?>).joinToString(", ") { t -> lit(t) }
                        "CatalogFeed(${lit(it["id"])}, ${lit(it["outletId"])}, ${lit(it["section"])}, " +
                            "${lit(it["url"])}, " +
                            "listOf($topics), ${lit(it["checkedUrl"])})"
                    },
                ),
            )

        val out = StringBuilder()
        out.append("// Generated by :shared:generateCatalogSource from catalog/catalog.json. Do not edit.\n")
        out.append("package app.newz.catalog\n\n")
        out.append("internal object CatalogData {\n")
        for ((name, type, entries) in sections) {
            val parts = entries.chunked(chunk).ifEmpty { listOf(emptyList()) }
            val body = parts.indices.joinToString(" + ") { "$name$it()" }
            out.append("    fun $name(): List<$type> = $body\n\n")
            parts.forEachIndexed { index, part ->
                out.append("    private fun $name$index(): List<$type> =\n        listOf(\n")
                part.forEach { out.append("            ").append(it).append(",\n") }
                out.append("        )\n\n")
            }
        }
        out.append("}\n")

        val file = outputDir.get().file("app/newz/catalog/CatalogData.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(out.toString())
    }
}

val generateCatalogSource by tasks.registering(GenerateCatalogSource::class) {
    description = "Generates CatalogData.kt from catalog/catalog.json."
    catalogJson.set(rootProject.layout.projectDirectory.file("catalog/catalog.json"))
    outputDir.set(layout.buildDirectory.dir("generated/catalog/commonMain"))
}

