/**
 * Turns catalog/catalog.json into CatalogData.kt (SPEC S26) and catalog/zip-table.csv into
 * ZipData.kt (SPEC S29). Lists are split into functions of at most 50 entries so no generated
 * method nears the JVM's 64 KB method limit. Unknown JSON keys are ignored and optional keys
 * default, so later phases can add fields.
 */
abstract class GenerateCatalogSource : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val catalogJson: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val zipTable: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val chunk = 50

        @Suppress("UNCHECKED_CAST")
        val root = groovy.json.JsonSlurper().parse(catalogJson.get().asFile) as Map<String, Any?>

        fun lit(value: Any?): String {
            if (value == null) return "null"
            val escaped =
                value
                    .toString()
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("\$", "\\\$")
                    .replace("\n", "\\n")
                    .replace("\r", "\\r")
            return "\"$escaped\""
        }

        fun list(key: String): List<Map<String, Any?>> {
            @Suppress("UNCHECKED_CAST")
            return (root[key] as? List<Map<String, Any?>>).orEmpty()
        }

        val paywalls = mapOf("none" to "NONE", "metered" to "METERED", "hard" to "HARD")
        val sections =
            listOf(
                Triple(
                    "topics",
                    "Topic",
                    list("topics").map { "Topic(${lit(it["id"])}, ${lit(it["name"])}, ${lit(it["description"])})" },
                ),
                Triple(
                    "outlets",
                    "Outlet",
                    list("outlets").map {
                        val paywall =
                            paywalls[it["paywall"]] ?: error("Outlet ${it["id"]}: bad paywall ${it["paywall"]}")
                        val popularity = (it["popularity"] as Number).toDouble()
                        "Outlet(${lit(it["id"])}, ${lit(it["name"])}, ${lit(it["domain"])}, " +
                            "PaywallStatus.$paywall, $popularity)"
                    },
                ),
                Triple(
                    "feeds",
                    "CatalogFeed",
                    list("feeds").map {
                        @Suppress("UNCHECKED_CAST")
                        val topics = (it["topics"] as List<Any?>).joinToString(", ") { t -> lit(t) }
                        "CatalogFeed(${lit(it["id"])}, ${lit(it["outletId"])}, ${lit(it["section"])}, " +
                            "${lit(it["url"])}, " +
                            "listOf($topics), ${lit(it["checkedUrl"])}, ${lit(it["metroId"])})"
                    },
                ),
                Triple(
                    "metros",
                    "Metro",
                    list("metros").map {
                        val population = (it["population"] as Number).toInt()
                        val lat = (it["lat"] as Number).toDouble()
                        val lon = (it["lon"] as Number).toDouble()
                        "Metro(${lit(it["id"])}, ${lit(it["cbsa"])}, ${lit(it["name"])}, $population, $lat, $lon)"
                    },
                ),
            )

        val out = StringBuilder()
        out.append("// Generated by :shared:generateCatalogSource from catalog/catalog.json. Do not edit.\n")
        out.append("package app.newz.catalog\n\n")
        out.append("internal object CatalogData {\n")
        for ((name, type, entries) in sections) {
            val parts = entries.chunked(chunk).ifEmpty { listOf(emptyList()) }
            val body = parts.indices.joinToString(" + ") { "$name$it()" }
            out.append("    fun $name(): List<$type> = $body\n\n")
            parts.forEachIndexed { index, part ->
                out.append("    private fun $name$index(): List<$type> =\n        listOf(\n")
                part.forEach { out.append("            ").append(it).append(",\n") }
                out.append("        )\n\n")
            }
        }
        out.append("}\n")

        val file = outputDir.get().file("app/newz/catalog/CatalogData.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(out.toString())

        generateZipData(list("metros").map { it["id"].toString() })
    }

    /**
     * Packs zip-table.csv as big-endian records of zip (Int), lat and lon (Int, microdegrees / 100)
     * and metro index (Byte into the catalog's metros, -1 for none), sorted by zip, then writes
     * them base64-encoded in string literals under 60,000 chars (a JVM class constant holds 65,535).
     */
    private fun generateZipData(metroIds: List<String>) {
        val metroIndex = metroIds.withIndex().associate { (index, id) -> id to index }
        require(metroIds.size < Byte.MAX_VALUE) { "Too many metros for a byte index: ${metroIds.size}" }
        val rows =
            zipTable
                .get()
                .asFile
                .readLines()
                .drop(1)
                .filter { it.isNotBlank() }
                .map { line ->
                    val cells = line.split(',')
                    require(cells.size == 4 && cells[0].length == 5) { "Bad zip-table row: $line" }
                    val metro =
                        if (cells[3] == "-") {
                            -1
                        } else {
                            metroIndex[cells[3]] ?: error("zip-table metro ${cells[3]} is not in catalog.json")
                        }
                    val lat = Math.round(cells[1].toDouble() * 10_000).toInt()
                    val lon = Math.round(cells[2].toDouble() * 10_000).toInt()
                    listOf(cells[0].toInt(), lat, lon, metro)
                }.sortedBy { it[0] }
        val recordBytes = 13
        val buffer = ByteBuffer.allocate(rows.size * recordBytes)
        for ((zip, lat, lon, metro) in rows) {
            buffer
                .putInt(zip)
                .putInt(lat)
                .putInt(lon)
                .put(metro.toByte())
        }
        val encoded = Base64.getEncoder().encodeToString(buffer.array())
        val chunks = encoded.chunked(59_996)

        val out = StringBuilder()
        out.append("// Generated by :shared:generateCatalogSource from catalog/zip-table.csv. Do not edit.\n")
        out.append("package app.newz.catalog\n\n")
        out.append("/**\n")
        out.append(" * The bundled zip table: $recordBytes-byte big-endian records of zip (Int), lat and lon\n")
        out.append(" * (Int, microdegrees / 100) and metro index (Byte into [METRO_IDS], -1 for none), sorted\n")
        out.append(" * by zip, base64-encoded in chunks that each decode on their own.\n")
        out.append(" */\n")
        out.append("internal object ZipData {\n")
        out.append("    const val RECORD_BYTES = $recordBytes\n\n")
        out.append("    const val COUNT = ${rows.size}\n\n")
        out.append("    val METRO_IDS: List<String> =\n        listOf(\n")
        metroIds.forEach { out.append("            \"").append(it).append("\",\n") }
        out.append("        )\n\n")
        out.append("    fun chunks(): Array<String> =\n        arrayOf(\n")
        chunks.forEach { out.append("            \"").append(it).append("\",\n") }
        out.append("        )\n")
        out.append("}\n")

        val file = outputDir.get().file("app/newz/catalog/ZipData.kt").asFile
        file.writeText(out.toString())
    }
}

