// Xcode may be installed without an iOS simulator runtime; the iOS test binary is still
// compiled and linked, but running it needs a simulator, so skip only the run step then.
val hasIosSimulatorRuntime =
    providers
        .exec {
            commandLine("xcrun", "simctl", "list", "runtimes")
            isIgnoreExitValue = true
        }.standardOutput.asText
        .map { it.contains("iOS ") }

tasks.withType<org.jetbrains.kotlin.gradle.targets.native.tasks.KotlinNativeSimulatorTest>().configureEach {
    onlyIf("an iOS simulator runtime is installed") { hasIosSimulatorRuntime.getOrElse(false) }
}

/**
 * Probes every catalog feed (or a candidates file) through the app's guarded HTTP client and
 * parser, and writes catalog/health-report.md. Run it via scripts/check-catalog-feeds.
 */
abstract class CheckCatalogFeeds : JavaExec() {
    @get:Input
    @get:Optional
    @get:org.gradle.api.tasks.options.Option(
        option = "file",
        description = "Probe this catalog-shaped JSON file instead of catalog/catalog.json.",
    )
    abstract val feedFile: Property<String>

    @get:Input
    @get:Optional
    @get:org.gradle.api.tasks.options.Option(
        option = "report",
        description = "Write the Markdown report here instead of catalog/health-report.md.",
    )
    abstract val reportFile: Property<String>

    @get:Input
    @get:Optional
    @get:org.gradle.api.tasks.options.Option(
        option = "json",
        description = "Also write per-feed results as JSON to this path.",
    )
    abstract val jsonFile: Property<String>

    @TaskAction
    override fun exec() {
        val extra = mutableListOf<String>()
        feedFile.orNull?.let { extra += listOf("--file", it) }
        reportFile.orNull?.let { extra += listOf("--report", it) }
        jsonFile.orNull?.let { extra += listOf("--json", it) }
        args(extra)
        super.exec()
    }
}

tasks.register<CheckCatalogFeeds>("checkCatalogFeeds") {
    description = "Checks that every bundled catalog feed is reachable, parseable and fresh."
    val main = kotlin.jvm().compilations.getByName("main")
    classpath(main.output.allOutputs, main.runtimeDependencyFiles)
    mainClass.set("app.newz.tools.CheckCatalogFeedsKt")
    workingDir = rootProject.projectDir
}
